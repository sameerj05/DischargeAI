/**
 * Builds docs/swagger.html: a standalone Swagger UI page with the current openapi.yaml embedded.
 *   npm run docs
 * test/swagger-docs.test.ts fails when the committed page drifts from openapi.yaml.
 * The page loads Swagger UI from a pinned jsDelivr copy, so it needs internet to render. "Try it
 * out" only works on the live page (http://localhost:4000/docs): a file opened from disk has no
 * origin the API allows.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import YAML from "yaml";

export const SWAGGER_UI_VERSION = "5.33.1";
export const OPENAPI_PATH = join(import.meta.dirname, "..", "openapi.yaml");
export const SWAGGER_HTML_PATH = join(import.meta.dirname, "..", "docs", "swagger.html");

/** JSON that is safe inside a <script> element (no early </script>, no U+2028/2029 line breaks). */
function inlineJson(value: unknown): string {
  return JSON.stringify(value, null, 2).replace(/</g, "\\u003c").replaceAll(String.fromCharCode(0x2028), "\\u2028").replaceAll(String.fromCharCode(0x2029), "\\u2029");
}

export function renderSwaggerHtml(yamlText: string): string {
  const spec = YAML.parse(yamlText) as { info?: { title?: string; version?: string }; openapi?: string };
  const title = `${spec.info?.title ?? "API"} ${spec.info?.version ?? ""}`.trim();
  const cdn = `https://cdn.jsdelivr.net/npm/swagger-ui-dist@${SWAGGER_UI_VERSION}`;
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${title.replace(/</g, "&lt;")}</title>
  <link rel="stylesheet" href="${cdn}/swagger-ui.css">
</head>
<body>
  <!-- Generated by scripts/swagger-docs.ts from openapi.yaml (OpenAPI ${spec.openapi}). Edit openapi.yaml, then run: npm run docs -->
  <div id="swagger-ui"></div>
  <script src="${cdn}/swagger-ui-bundle.js"></script>
  <script>
    const spec = ${inlineJson(spec)};
    window.onload = () => SwaggerUIBundle({ spec, dom_id: "#swagger-ui", deepLinking: true, tryItOutEnabled: false });
  </script>
</body>
</html>
`;
}

const isMain = process.argv[1]?.endsWith("swagger-docs.ts");
if (isMain) {
  writeFileSync(SWAGGER_HTML_PATH, renderSwaggerHtml(readFileSync(OPENAPI_PATH, "utf8")));
  console.log(`wrote ${SWAGGER_HTML_PATH}`);
}
